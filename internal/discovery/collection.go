package discovery

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"Postwoman/internal/model"

	"github.com/google/uuid"
)

// BuildCollection renders reviewed endpoints as a Postman v2.1 collection that
// Postwoman's native importer accepts. Secrets are never hardcoded: dynamic
// values become collection variables or placeholders.
func BuildCollection(session *model.DiscoverySession, req model.DiscoveryGenerateRequest) (string, error) {
	if session == nil {
		return "", fmt.Errorf("discovery session not found")
	}
	name := strings.TrimSpace(req.CollectionName)
	if name == "" {
		name = strings.TrimSpace(session.Options.CollectionName)
	}
	if name == "" {
		name = "Discovered API"
	}
	baseURL := strings.TrimSpace(req.BaseURL)
	if baseURL == "" {
		baseURL = strings.TrimSpace(session.Options.BaseURL)
	}
	if baseURL == "" {
		baseURL = "http://localhost:8080"
	}
	baseURL = strings.TrimRight(baseURL, "/")

	edits := map[string]model.DiscoveryEndpointEdit{}
	for _, edit := range req.Endpoints {
		edits[edit.ID] = edit
	}

	folders := map[string][]map[string]any{}
	used := 0
	for _, ep := range session.Endpoints {
		edit, hasEdit := edits[ep.ID]
		if hasEdit {
			if !edit.Selected {
				continue
			}
		} else if !ep.Selected {
			continue
		}
		selected := ep
		if hasEdit {
			if strings.TrimSpace(edit.Name) != "" {
				selected.Name = edit.Name
			}
			if strings.TrimSpace(edit.Description) != "" {
				selected.Description = edit.Description
			}
			if strings.TrimSpace(edit.Folder) != "" {
				selected.Folder = edit.Folder
			}
		}
		folder := strings.TrimSpace(selected.Folder)
		if folder == "" {
			folder = "General"
		}
		folders[folder] = append(folders[folder], requestItem(selected, baseURL))
		used++
	}
	if used == 0 {
		return "", fmt.Errorf("no endpoints were selected for import")
	}

	folderNames := make([]string, 0, len(folders))
	for folder := range folders {
		folderNames = append(folderNames, folder)
	}
	sort.Slice(folderNames, func(i, j int) bool {
		if folderNames[i] == "General" {
			return false
		}
		if folderNames[j] == "General" {
			return true
		}
		return folderNames[i] < folderNames[j]
	})
	items := make([]map[string]any, 0, len(folderNames))
	for _, folder := range folderNames {
		items = append(items, map[string]any{
			"name": folder,
			"item": folders[folder],
		})
	}

	collection := map[string]any{
		"info": map[string]any{
			"_postman_id": uuid.NewString(),
			"name":        name,
			"description": "Generated by the Postwoman API Discovery Agent. Review before relying on inferred values.",
			"schema":      "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
		},
		"item": items,
		"variable": []map[string]any{
			{"key": "baseUrl", "value": baseURL, "type": "string"},
			{"key": "authToken", "value": "", "type": "string"},
		},
	}
	encoded, err := json.MarshalIndent(collection, "", "  ")
	if err != nil {
		return "", err
	}
	return string(encoded), nil
}
